import { PrismaPg } from "@prisma/adapter-pg";
import pkg from "@prisma/client";
const { PrismaClient } = pkg;
import dotenv from "dotenv";
dotenv.config();
const prisma = new PrismaClient({ adapter: new PrismaPg({ connectionString: process.env.DATABASE_URL }) });
const tid = (await prisma.tenant.findUniqueOrThrow({ where: { slug: "omega" } })).id;
const products = await prisma.product.findMany({ where: { tenantId: tid }, select: { id: true, name: true, unit: true, packSize: true, packLabel: true, packUnit: { select: { name: true } }, sellsDirectly: true }, orderBy: { name: "asc" } });
const units = await prisma.unitOfMeasure.findMany({ where: { tenantId: tid }, select: { id: true, name: true, systemKey: true, measurementKind: true }, orderBy: { name: "asc" } });
console.log(JSON.stringify({ products, units }));
await prisma.$disconnect();
